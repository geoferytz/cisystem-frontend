@Injectable({ providedIn: 'root' })
export class TranslationService {
  private readonly storageKey = 'cisystem-language';
  private readonly fallbackLang: AppLanguage = 'en';
  readonly availableLangs: AppLanguage[] = ['en', 'sw', 'fr', 'es', 'ar'];
  private readonly _currentLang = signal<AppLanguage>(this.loadLanguage());
  readonly currentLang = this._currentLang.asReadonly();
  readonly currentLangLabel = computed(() => this._currentLang().toUpperCase());

  setLanguage(lang: string): void {
    const nextLang = this.isSupportedLanguage(lang) ? lang : this.fallbackLang;
    this._currentLang.set(nextLang);
    this.saveLanguage(nextLang);
  }

  translate(key: string): string {
    const lang = this._currentLang();
    const typedKey = key as TranslationKey;
    return translations[lang][typedKey] || translations[this.fallbackLang][typedKey] || key;
  }

  private loadLanguage(): AppLanguage {
    if (typeof window === 'undefined') return this.fallbackLang;
    try {
      const stored = localStorage.getItem(this.storageKey);
      // Earlier versions force-set 'sw' for all users; migrate that stored value to the new default once.
      if (stored === 'sw') {
        this.saveLanguage(this.fallbackLang);
        return this.fallbackLang;
      }
      return this.isSupportedLanguage(stored) ? stored : this.fallbackLang;
    } catch {
      return this.fallbackLang;
    }
  }

  private saveLanguage(lang: AppLanguage): void {
    if (typeof window === 'undefined') return;
    try {
      localStorage.setItem(this.storageKey, lang);
    } catch {}
  }

  private isSupportedLanguage(lang: unknown): lang is AppLanguage {
    return typeof lang === 'string' && this.availableLangs.includes(lang as AppLanguage);
  }
}
